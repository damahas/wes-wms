<template>
  <div class="app-container">
    <div class="main-panel p16">
      <query-form
        :config="queryConfig"
        v-model:visible="showSearch"
        v-model="queryParams"
        @query="handleQuery"
        @reset="resetQuery"
      />

    <!-- 操作按钮 -->
    <el-row :gutter="10" class="mb8">
      <el-col :span="1.5">
        <el-button type="primary" plain icon="Plus" @click="handleAdd" v-hasPermi="['wms:delivery:add']">{{ t('common.add') }}</el-button>
      </el-col>
      <el-col :span="1.5">
        <el-button type="success" plain icon="Edit" :disabled="single" @click="handleUpdate" v-hasPermi="['wms:delivery:edit']">{{ t('common.edit') }}</el-button>
      </el-col>
      <el-col :span="1.5">
        <el-button type="danger" plain icon="Delete" :disabled="multiple" @click="handleDelete" v-hasPermi="['wms:delivery:remove']">{{ t('common.delete') }}</el-button>
      </el-col>
        <right-toolbar
          v-model:showSearch="showSearch"
          @queryTable="getList"
        ></right-toolbar>
    </el-row>

    <!-- 列表 -->
    <el-table v-loading="loading" :data="deliveryList" @selection-change="handleSelectionChange">
      <el-table-column type="selection" width="55" align="center" />
      <el-table-column :label="t('wms.delivery.deliveryNo')" align="center" prop="deliveryNo" :show-overflow-tooltip="true" />



      <el-table-column :label="t('common.createTime')" align="center" prop="createTime" min-width="170" />
      <el-table-column :label="t('common.actions')" align="center" width="150" class-name="small-padding fixed-width">
        <template #default="scope">
          <el-button v-if="scope.row.deliveryStatus !== 'shipped' && scope.row.deliveryStatus !== 'delivered'" link type="success" icon="Promotion" @click="handleExecute(scope.row)" v-hasPermi="['wms:delivery:edit']">{{ t('wms.delivery.execute') }}</el-button>
          <el-button link type="primary" icon="Edit" @click="handleUpdate(scope.row)" v-hasPermi="['wms:delivery:edit']">{{ t('common.edit') }}</el-button>
          <el-button link type="danger" icon="Delete" @click="handleDelete(scope.row)" v-hasPermi="['wms:delivery:remove']">{{ t('common.delete') }}</el-button>
        </template>
      </el-table-column>
        <el-table-column :label="t('wms.common.warehouse')" align="center" :show-overflow-tooltip="true">
      <template #default="scope">
        {{ scope.row.warehouse?.warehouseName || "-" }}
      </template>
    </el-table-column>
    <el-table-column :label="t('wms.zone.zoneCode')" align="center" :show-overflow-tooltip="true">
      <template #default="scope">
        {{ scope.row.zone?.zoneCode || "-" }}
      </template>
    </el-table-column>
    <el-table-column :label="t('wms.common.zone')" align="center" :show-overflow-tooltip="true">
      <template #default="scope">
        {{ scope.row.zone?.zoneName || "-" }}
      </template>
    </el-table-column>
    <el-table-column :label="t('wms.delivery.customer')" align="center" :show-overflow-tooltip="true">
      <template #default="scope">
        {{ scope.row.customer?.partnerName || "-" }}
      </template>
    </el-table-column>
</el-table>

    <pagination
      v-show="total > 0"
      :total="total"
      v-model:page="queryParams.pageNum"
      v-model:limit="queryParams.pageSize"
      @pagination="getList"
    />

    <!-- 添加或修改对话框 -->
    <el-dialog :title="title" v-model="open" width="700px" append-to-body>
      <el-form ref="deliveryRef" :model="form" :rules="rules" label-width="auto">
        <el-form-item :label="t('wms.delivery.deliveryNo')" prop="deliveryNo">
          <el-input v-model="form.deliveryNo" :placeholder="t('wms.receiving.ph.autoGenerated')" maxlength="50" :readonly="true" />
        </el-form-item>

        <el-form-item :label="t('wms.delivery.warehouseId')" prop="warehouseId">
          <el-input v-model="form.warehouseId" :placeholder="t('wms.delivery.ph.inputWarehouseId')" />
        </el-form-item>

        <el-form-item :label="t('wms.delivery.zoneId')" prop="zoneId">
          <el-input v-model="form.zoneId" :placeholder="t('wms.delivery.ph.inputZoneId')" />
        </el-form-item>

        <el-form-item :label="t('wms.delivery.customerId')" prop="customerId">
          <el-input v-model="form.customerId" :placeholder="t('wms.delivery.ph.inputCustomerId')" />
        </el-form-item>

        <el-form-item :label="t('wms.delivery.deliveryDate')" prop="deliveryDate">
          <el-date-picker v-model="form.deliveryDate" type="datetime" value-format="YYYY-MM-DD HH:mm:ss" :placeholder="t('wms.delivery.ph.inputDeliveryDate')" style="width: 100%" />
        </el-form-item>
        <el-form-item :label="t('wms.receipt.totalQuantity')" prop="totalQuantity">
          <el-input-number controls-position="right" v-model="form.totalQuantity" :min="0" :controls="false" style="width: 100%" />
        </el-form-item>
        <el-form-item :label="t('wms.delivery.totalAmount')" prop="totalAmount">
          <el-input-number controls-position="right" v-model="form.totalAmount" :min="0" :precision="2" :controls="false" style="width: 100%" />
        </el-form-item>
        <el-form-item :label="t('wms.delivery.carrier')" prop="carrierName">
          <el-input v-model="form.carrierName" :placeholder="t('wms.delivery.ph.inputCarrier')" maxlength="100" />
        </el-form-item>
        <el-form-item :label="t('wms.delivery.waybillNo')" prop="waybillNo">
          <el-input v-model="form.waybillNo" :placeholder="t('wms.delivery.ph.inputWaybillNo')" maxlength="100" />
        </el-form-item>
        <el-form-item :label="t('wms.delivery.packageCount')" prop="packageCount">
          <el-input-number controls-position="right" v-model="form.packageCount" :min="0" :controls="false" style="width: 100%" />
        </el-form-item>
        <el-form-item :label="t('wms.delivery.totalWeight')" prop="totalWeight">
          <el-input-number controls-position="right" v-model="form.totalWeight" :min="0" :precision="2" :controls="false" style="width: 100%" />
        </el-form-item>
        <el-form-item :label="t('wms.delivery.deliveryStatus')" prop="deliveryStatus">
          <el-input v-model="form.deliveryStatus" :placeholder="t('wms.delivery.ph.inputStatus')" maxlength="20" />
        </el-form-item>
        <el-form-item :label="t('wms.delivery.shipTime')" prop="shipTime">
          <el-date-picker v-model="form.shipTime" type="datetime" value-format="YYYY-MM-DD HH:mm:ss" :placeholder="t('wms.delivery.ph.inputShipTime')" style="width: 100%" />
        </el-form-item>
        <el-form-item :label="t('wms.delivery.signTime')" prop="signTime">
          <el-date-picker v-model="form.signTime" type="datetime" value-format="YYYY-MM-DD HH:mm:ss" :placeholder="t('wms.delivery.ph.inputSignTime')" style="width: 100%" />
        </el-form-item>
        <el-form-item :label="t('wms.delivery.operatorId')" prop="operatorId">
          <el-input v-model="form.operatorId" :placeholder="t('wms.delivery.ph.inputOperatorId')" />
        </el-form-item>

      </el-form>
      <template #footer>
        <div class="dialog-footer">
          <el-button type="primary" @click="submitForm">{{ t('common.submit') }}</el-button>
          <el-button @click="cancel">{{ t('common.cancel') }}</el-button>
        </div>
      </template>
    </el-dialog>
    </div>
  </div>
</template>

<script setup name="WmsDelivery">
import { ref, reactive, toRefs, computed } from "vue";
import { ElMessage, ElMessageBox } from "element-plus";
import { useI18n } from "vue-i18n";
import {
  listDelivery,
  getDelivery,
  addDelivery,
  updateDelivery,
  delDelivery,
  executeDelivery,
} from "@/api/wms/delivery";
import QueryForm from "@/components/QueryForm/index.vue";
import RightToolbar from "@/components/RightToolbar/index.vue";

const { t } = useI18n();
const deliveryRef = ref(null);
const deliveryList = ref([]);
const open = ref(false);
const loading = ref(true);
const ids = ref([]);
const single = ref(true);
const multiple = ref(true);
const total = ref(0);
const title = ref("");

const showSearch = ref(true);

const data = reactive({
  form: {},
  queryParams: {
    pageNum: 1,
    pageSize: 10,
    keywords: undefined,
  },
  rules: {

  },
});

const { form, queryParams, rules } = toRefs(data);

const queryConfig = computed(() => [
  {
    label: t('wms.common.keywords'),
    prop: "keywords",
    type: "input",
    placeholder: t('common.input'),
  },
]);

/** 查询列表 */
function getList() {
  loading.value = true;
  listDelivery(queryParams.value).then((res) => {
    deliveryList.value = res.rows || [];
    total.value = res.total || 0;
    loading.value = false;
  });
}

/** 标签页重新激活时由布局回调（是否刷新由页面决定） */
function tabRefresh() {
  getList();
}

/** 搜索 */
function handleQuery() {
  queryParams.value.pageNum = 1;
  getList();
}

/** 重置 */
function resetQuery() {
  queryParams.value = {
    keywords: undefined,
    pageNum: 1,
    pageSize: 10,
  };
  handleQuery();
}

/** 表单重置 */
function reset() {
  form.value = {
    deliveryId: undefined,
    deliveryNo: undefined,
    waveId: undefined,
    waveNo: undefined,
    warehouseId: undefined,
    warehouseName: undefined,
    zoneId: undefined,
    zoneCode: undefined,
    customerId: undefined,
    customerName: undefined,
    deliveryDate: undefined,
    totalQuantity: undefined,
    totalAmount: undefined,
    carrierName: undefined,
    waybillNo: undefined,
    packageCount: undefined,
    totalWeight: undefined,
    deliveryStatus: undefined,
    shipTime: undefined,
    signTime: undefined,
    operatorId: undefined,
    operatorName: undefined,
  };
  if (deliveryRef.value) deliveryRef.value.resetFields();
}

/** 新增 */
function handleAdd() {
  reset();
  open.value = true;
  title.value = t('wms.delivery.addTitle');
}

/** 修改 */
function handleUpdate(row) {
  reset();
  const id = row.deliveryId || ids.value[0];
  getDelivery(id).then((res) => {
    form.value = res.data || {};
    open.value = true;
    title.value = t('wms.delivery.editTitle');
  });
}

/** 提交 */
function submitForm() {
  deliveryRef.value.validate((valid) => {
    if (!valid) return;
    const api = form.value.deliveryId ? updateDelivery : addDelivery;
    api(form.value).then(() => {
      ElMessage.success(t('wms.common.savedSuccess'));
      open.value = false;
      getList();
    });
  });
}

/** 取消 */
function cancel() {
  open.value = false;
  reset();
}

/** 执行出库（发货） */
function handleExecute(row) {
  ElMessageBox.confirm(
    t('wms.delivery.executeConfirmMsg', { no: row.deliveryNo }),
    t('wms.delivery.executeConfirmTitle'),
    { confirmButtonText: t('wms.delivery.executeConfirmBtn'), cancelButtonText: t('common.cancel'), type: "warning" }
  )
    .then(() => executeDelivery(row.deliveryId))
    .then(() => {
      ElMessage.success(t('wms.delivery.executeSuccess'));
      getList();
    });
}

/** 删除 */
function handleDelete(row) {
  const delIds = row.deliveryId || ids.value.join(",");
  ElMessageBox.confirm(t('wms.common.deleteConfirm', { id: delIds }), t('wms.common.warning'), {
    confirmButtonText: t('common.confirm'),
    cancelButtonText: t('common.cancel'),
    type: "warning",
  })
    .then(() => delDelivery(delIds))
    .then(() => {
      getList();
      ElMessage.success(t('wms.common.deleteSuccess'));
    });
}

getList();
</script>
